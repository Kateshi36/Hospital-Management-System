using System.Data;
using System.Globalization;
using System.Text;
using HospitalManagementSystem.Helpers;
using HospitalManagementSystem.Models.MP12_Payment;
using MySqlConnector;

namespace HospitalManagementSystem.Repositories.MP12_Payment
{
    /// <summary>
    /// All SQL for Payment Processing and Billing Records (MP12, Step 16).
    ///
    /// RECORD A PAYMENT (RecordPayment - one transaction)
    ///   1. the bill row is locked (FOR UPDATE), so two cashiers paying the same bill are handled one after the other;
    ///   2. the bill must be Finalized; its balance is read again from v_bill_payment_summary (the screen's figure may be old);
    ///   3. every rule is checked again (Validate): amount above 0 and not above the balance, the method, the reference number
    ///      (required for Debit, Credit and Online), the cash tendered amount (not less than the amount);
    ///   4. the payment id PAY-YYYYMMDD-XXX is generated by GeneratorHelper inside this transaction (no gap if the save fails) and the payment is inserted.
    /// The payment status of a bill is never stored: v_bill_payment_summary derives it from the payments
    /// (Outstanding -> Partially Paid -> Fully Paid), so it can never disagree with the payment rows.
    /// </summary>
    public class PaymentRepository
    {
        private static readonly string SummarySelect =
            "SELECT s.bill_id, s.grand_total, s.amount_paid, s.balance, s.payment_status, " +
            "       p.patient_id, CONCAT(p.first_name, ' ', p.last_name) AS patient_name, b.finalized_at " +
            "FROM v_bill_payment_summary s " +
            "JOIN bills b ON b.bill_id = s.bill_id " +
            "JOIN patients p ON p.patient_id = b.patient_id " +
            "WHERE s.status = '" + PaymentRules.BillFinalized + "'";

        // ------------------------------------------------------------------
        // Helpers
        // ------------------------------------------------------------------

        private static DataTable Query(MySqlConnection? conn, MySqlTransaction? tx, string sql, params MySqlParameter[] parameters) =>
            conn == null
                ? DatabaseHelper.ExecuteQuery(sql, parameters)
                : DatabaseHelper.ExecuteQuery(conn, tx, sql, parameters);

        /// <summary>Adds "AND (col1 LIKE @w0 OR col2 LIKE @w0) AND (...)" for every word typed in a search box.</summary>
        private static void AppendWords(StringBuilder sql, List<MySqlParameter> parameters, string? text, params string[] columns)
        {
            if (string.IsNullOrWhiteSpace(text)) return;
            string[] words = text.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            for (int i = 0; i < words.Length; i++)
            {
                string name = "@w" + i.ToString(CultureInfo.InvariantCulture);
                sql.Append(" AND (").Append(string.Join(" OR ", columns.Select(c => c + " LIKE " + name))).Append(')');
                string escaped = words[i].Replace("\\", "\\\\").Replace("%", "\\%").Replace("_", "\\_");
                parameters.Add(DatabaseHelper.Param(name, "%" + escaped + "%"));
            }
        }

        private static PayableBill ReadBill(DataRow r) => new PayableBill
        {
            BillId = DatabaseHelper.GetString(r, "bill_id"),
            PatientId = DatabaseHelper.GetString(r, "patient_id"),
            PatientName = DatabaseHelper.GetString(r, "patient_name"),
            BillDate = DatabaseHelper.GetNullableDate(r, "finalized_at") ?? DateTime.Now,
            GrandTotal = DatabaseHelper.GetDecimal(r, "grand_total"),
            AmountPaid = DatabaseHelper.GetDecimal(r, "amount_paid"),
            Balance = DatabaseHelper.GetDecimal(r, "balance"),
            PaymentStatus = DatabaseHelper.GetString(r, "payment_status")
        };

        // ------------------------------------------------------------------
        // Lists
        // ------------------------------------------------------------------

        public List<PaymentMethod> GetMethods() => PaymentRules.Methods.ToList();

        /// <summary>Finalized bills that still have a balance (oldest first).</summary>
        public List<PayableBill> GetPayableBills(string? text)
        {
            var sql = new StringBuilder(SummarySelect + " AND s.balance > 0");
            var parameters = new List<MySqlParameter>();
            AppendWords(sql, parameters, text, "s.bill_id", "p.patient_id", "p.first_name", "p.last_name");
            sql.Append(" ORDER BY b.finalized_at, b.bill_id LIMIT ").Append(PaymentRules.PayableLimit.ToString(CultureInfo.InvariantCulture));
            return DatabaseHelper.ExecuteQuery(sql.ToString(), parameters.ToArray()).Rows.Cast<DataRow>().Select(ReadBill).ToList();
        }

        public PayableBill? GetBill(string billId)
        {
            DataTable table = DatabaseHelper.ExecuteQuery(SummarySelect + " AND s.bill_id = @id", DatabaseHelper.Param("@id", billId));
            return table.Rows.Count == 0 ? null : ReadBill(table.Rows[0]);
        }

        /// <summary>
        /// Billing Records: every finalized bill, filtered by bill ID / patient (words), bill date range and payment status.
        /// paymentStatus: "" = all, otherwise Outstanding, Partially Paid or Fully Paid.
        /// </summary>
        public List<PayableBill> GetRecords(string? text, DateTime? from, DateTime? to, string? paymentStatus)
        {
            var sql = new StringBuilder(SummarySelect);
            var parameters = new List<MySqlParameter>();
            AppendWords(sql, parameters, text, "s.bill_id", "p.patient_id", "p.first_name", "p.last_name");
            if (from.HasValue)
            {
                sql.Append(" AND DATE(b.finalized_at) >= @from");
                parameters.Add(DatabaseHelper.Param("@from", from.Value.Date));
            }
            if (to.HasValue)
            {
                sql.Append(" AND DATE(b.finalized_at) <= @to");
                parameters.Add(DatabaseHelper.Param("@to", to.Value.Date));
            }
            if (!string.IsNullOrEmpty(paymentStatus))
            {
                sql.Append(" AND s.payment_status = @status");
                parameters.Add(DatabaseHelper.Param("@status", paymentStatus));
            }
            sql.Append(" ORDER BY b.finalized_at DESC, b.bill_id DESC LIMIT ").Append(PaymentRules.ListLimit.ToString(CultureInfo.InvariantCulture));
            return DatabaseHelper.ExecuteQuery(sql.ToString(), parameters.ToArray()).Rows.Cast<DataRow>().Select(ReadBill).ToList();
        }

        /// <summary>The full payment history of a bill, oldest first.</summary>
        public List<PaymentRecord> GetPayments(string billId)
        {
            DataTable table = DatabaseHelper.ExecuteQuery(
                "SELECT pm.payment_id, pm.amount, pm.reference_number, pm.tendered_amount, pm.payment_datetime, " +
                "       pm.payment_method AS method_name, u.full_name AS received_by " +
                "FROM payments pm " +
                "JOIN users u ON u.user_id = pm.received_by_user_id " +
                "WHERE pm.bill_id = @id ORDER BY pm.payment_datetime, pm.payment_id",
                DatabaseHelper.Param("@id", billId));

            return table.Rows.Cast<DataRow>().Select(r => new PaymentRecord
            {
                PaymentId = DatabaseHelper.GetString(r, "payment_id"),
                Amount = DatabaseHelper.GetDecimal(r, "amount"),
                MethodName = DatabaseHelper.GetString(r, "method_name"),
                ReferenceNumber = DatabaseHelper.GetString(r, "reference_number"),
                Tendered = r["tendered_amount"] == DBNull.Value ? null : DatabaseHelper.GetDecimal(r, "tendered_amount"),
                ReceivedBy = DatabaseHelper.GetString(r, "received_by"),
                PaidAt = DatabaseHelper.GetNullableDate(r, "payment_datetime") ?? DateTime.Now
            }).ToList();
        }

        // ------------------------------------------------------------------
        // Rules
        // ------------------------------------------------------------------

        /// <summary>
        /// Every rule that needs no database. The screen shows each message next to its field; the repository calls it again
        /// with a fresh balance inside the save transaction.
        /// </summary>
        public static List<PaymentIssue> Validate(PaymentInput input, PayableBill? bill, PaymentMethod? method)
        {
            var issues = new List<PaymentIssue>();

            if (bill == null)
            {
                issues.Add(new PaymentIssue(PaymentField.Bill, "Choose the bill to pay."));
                return issues;
            }
            if (bill.Balance <= 0)
                issues.Add(new PaymentIssue(PaymentField.Bill, "This bill is already fully paid."));

            if (input.Amount <= 0)
                issues.Add(new PaymentIssue(PaymentField.Amount, "The payment amount must be greater than zero."));
            else if (BillMath(input.Amount) != input.Amount)
                issues.Add(new PaymentIssue(PaymentField.Amount, "The payment amount can have at most 2 decimal places."));
            else if (input.Amount > PaymentRules.MaxAmount)
                issues.Add(new PaymentIssue(PaymentField.Amount, $"The payment amount can be at most {PaymentRules.MaxAmount:N2}."));
            else if (bill.Balance > 0 && input.Amount > bill.Balance)
                issues.Add(new PaymentIssue(PaymentField.Amount,
                    $"The payment ({SettingsHelper.FormatMoney(input.Amount)}) cannot be more than the outstanding balance ({SettingsHelper.FormatMoney(bill.Balance)})."));

            if (method == null)
            {
                issues.Add(new PaymentIssue(PaymentField.Method, "Choose the payment method."));
            }
            else
            {
                string reference = (input.ReferenceNumber ?? string.Empty).Trim();
                if (method.RequiresReference && reference.Length == 0)
                    issues.Add(new PaymentIssue(PaymentField.Reference, $"A reference number is required for {method.Name} payments."));
                if (reference.Length > PaymentRules.MaxReference)
                    issues.Add(new PaymentIssue(PaymentField.Reference, $"The reference number can have at most {PaymentRules.MaxReference} characters."));

                if (method.Id == PaymentRules.MethodCash && input.Tendered.HasValue)
                {
                    if (input.Tendered.Value <= 0 || BillMath(input.Tendered.Value) != input.Tendered.Value || input.Tendered.Value > PaymentRules.MaxAmount)
                        issues.Add(new PaymentIssue(PaymentField.Tendered, "The tendered amount must be greater than zero with at most 2 decimal places."));
                    else if (input.Amount > 0 && input.Tendered.Value < input.Amount)
                        issues.Add(new PaymentIssue(PaymentField.Tendered, "The cash tendered cannot be less than the amount paid."));
                }
            }

            return issues;
        }

        private static decimal BillMath(decimal value) => Math.Round(value, 2, MidpointRounding.AwayFromZero);

        // ------------------------------------------------------------------
        // Saving
        // ------------------------------------------------------------------

        public Receipt RecordPayment(PaymentInput input)
        {
            string paymentId = DatabaseHelper.ExecuteInTransaction((conn, tx) =>
            {
                DataTable locked = DatabaseHelper.ExecuteQuery(conn, tx,
                    "SELECT status FROM bills WHERE bill_id = @id FOR UPDATE", DatabaseHelper.Param("@id", input.BillId));
                if (locked.Rows.Count == 0) throw new InvalidOperationException("This bill no longer exists. The list will be refreshed.");
                if (DatabaseHelper.GetString(locked.Rows[0], "status") != PaymentRules.BillFinalized)
                    throw new InvalidOperationException("Only a finalized bill can be paid.");

                DataTable fresh = DatabaseHelper.ExecuteQuery(conn, tx, SummarySelect + " AND s.bill_id = @id", DatabaseHelper.Param("@id", input.BillId));
                if (fresh.Rows.Count == 0) throw new InvalidOperationException("The bill could not be found.");
                PayableBill bill = ReadBill(fresh.Rows[0]);

                PaymentMethod? method = PaymentRules.Methods.FirstOrDefault(m => m.Id == input.Method);

                List<PaymentIssue> issues = Validate(input, bill, method);
                if (issues.Count > 0) throw new InvalidOperationException(string.Join(Environment.NewLine, issues.Select(i => i.Message)));

                string reference = (input.ReferenceNumber ?? string.Empty).Trim();
                decimal? tendered = method!.Id == PaymentRules.MethodCash ? input.Tendered : null;
                string id = GeneratorHelper.Generate(GeneratorHelper.Prefix.Payment, conn, tx);

                DatabaseHelper.ExecuteNonQuery(conn, tx,
                    "INSERT INTO payments (payment_id, bill_id, amount, payment_method, reference_number, tendered_amount, received_by_user_id) " +
                    "VALUES (@id, @bill, @amount, @method, @reference, @tendered, @user)",
                    DatabaseHelper.Param("@id", id),
                    DatabaseHelper.Param("@bill", input.BillId),
                    DatabaseHelper.Param("@amount", input.Amount),
                    DatabaseHelper.Param("@method", method.Id),
                    DatabaseHelper.Param("@reference", reference.Length == 0 ? null : reference),
                    DatabaseHelper.Param("@tendered", tendered),
                    DatabaseHelper.Param("@user", SessionManager.CurrentUserId));
                return id;
            });

            return GetReceipt(paymentId) ?? throw new InvalidOperationException("The payment was saved but its receipt could not be read back.");
        }

        /// <summary>
        /// The Official Receipt of one payment. "New balance" is the balance right after THIS payment
        /// (bill total minus every payment up to and including it), so a reprinted receipt always shows the same figures.
        /// </summary>
        public Receipt? GetReceipt(string paymentId)
        {
            DataTable table = DatabaseHelper.ExecuteQuery(
                "SELECT pm.payment_id, pm.amount, pm.reference_number, pm.tendered_amount, pm.payment_datetime, " +
                "       pm.payment_method AS method_name, u.full_name AS received_by, pm.bill_id, p.patient_id, " +
                "       CONCAT(p.first_name, ' ', p.last_name) AS patient_name, t.grand_total, " +
                "       (SELECT COALESCE(SUM(x.amount), 0) FROM payments x WHERE x.bill_id = pm.bill_id " +
                "          AND (x.payment_datetime < pm.payment_datetime " +
                "               OR (x.payment_datetime = pm.payment_datetime AND x.payment_id <= pm.payment_id))) AS paid_through " +
                "FROM payments pm " +
                "JOIN users u ON u.user_id = pm.received_by_user_id " +
                "JOIN bills b ON b.bill_id = pm.bill_id " +
                "JOIN patients p ON p.patient_id = b.patient_id " +
                "JOIN v_bill_totals t ON t.bill_id = pm.bill_id " +
                "WHERE pm.payment_id = @id",
                DatabaseHelper.Param("@id", paymentId));
            if (table.Rows.Count == 0) return null;

            DataRow r = table.Rows[0];
            decimal amount = DatabaseHelper.GetDecimal(r, "amount");
            decimal total = DatabaseHelper.GetDecimal(r, "grand_total");
            decimal through = DatabaseHelper.GetDecimal(r, "paid_through");
            decimal balance = total - through;

            return new Receipt
            {
                PaymentId = DatabaseHelper.GetString(r, "payment_id"),
                BillId = DatabaseHelper.GetString(r, "bill_id"),
                PatientId = DatabaseHelper.GetString(r, "patient_id"),
                PatientName = DatabaseHelper.GetString(r, "patient_name"),
                BillTotal = total,
                AmountPaid = amount,
                PaidBefore = through - amount,
                NewBalance = balance < 0 ? 0 : balance,
                MethodName = DatabaseHelper.GetString(r, "method_name"),
                ReferenceNumber = DatabaseHelper.GetString(r, "reference_number"),
                Tendered = r["tendered_amount"] == DBNull.Value ? null : DatabaseHelper.GetDecimal(r, "tendered_amount"),
                ReceivedBy = DatabaseHelper.GetString(r, "received_by"),
                PaidAt = DatabaseHelper.GetNullableDate(r, "payment_datetime") ?? DateTime.Now,
                StatusAfter = balance <= 0 ? PaymentRules.FullyPaid : PaymentRules.PartiallyPaid
            };
        }
    }

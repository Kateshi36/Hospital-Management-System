using System.Data;
using System.Globalization;
using System.Text;
using HospitalManagementSystem.Helpers;
using HospitalManagementSystem.Models.MP12_Payment;
using MySqlConnector;

namespace HospitalManagementSystem.Repositories.MP12_Payment
{
    /// <summary>
    /// All SQL for Payment Processing and Billing Records (MP12, Step 16).
    ///
    /// RECORD A PAYMENT (RecordPayment - one transaction)
    ///   1. the bill row is locked (FOR UPDATE), so two cashiers paying the same bill are handled one after the other;
    ///   2. the bill must be Finalized; its balance is read again from v_bill_payment_summary (the screen's figure may be old);
    ///   3. every rule is checked again (Validate): amount above 0 and not above the balance, the method, the reference number
    ///      (required for Debit, Credit and Online), the cash tendered amount (not less than the amount);
    ///   4. the payment id PAY-YYYYMMDD-XXX is generated by GeneratorHelper inside this transaction (no gap if the save fails) and the payment is inserted.
    /// The payment status of a bill is never stored: v_bill_payment_summary derives it from the payments
    /// (Outstanding -> Partially Paid -> Fully Paid), so it can never disagree with the payment rows.
    ///
    /// REFUNDS (RecordRefund): a recorded payment is never edited or deleted. Money given back is a new REVERSING row
    /// (payment_type 'Refund', id RFD-YYYYMMDD-XXX) linked to the payment, with the reason and the cashier; at most what is
    /// left of that payment can be refunded. The views subtract refunds, so the balance and status follow automatically.
    /// Every payment and refund is also written to audit_log.
    /// </summary>
    public class PaymentRepository
    {
        // finalized and voided bills (a voided bill stays visible in the records with its payments and refunds)
        private static readonly string SummarySelect =
            "SELECT s.bill_id, s.status, s.grand_total, s.amount_paid, s.amount_refunded, s.balance, s.payment_status, " +
            "       p.patient_id, CONCAT(p.first_name, ' ', p.last_name) AS patient_name, b.finalized_at " +
            "FROM v_bill_payment_summary s " +
            "JOIN bills b ON b.bill_id = s.bill_id " +
            "JOIN patients p ON p.patient_id = b.patient_id " +
            "WHERE s.status IN ('" + PaymentRules.BillFinalized + "', '" + PaymentRules.BillVoided + "')";

        // ------------------------------------------------------------------
        // Helpers
        // ------------------------------------------------------------------

        private static DataTable Query(MySqlConnection? conn, MySqlTransaction? tx, string sql, params MySqlParameter[] parameters) =>
            conn == null
                ? DatabaseHelper.ExecuteQuery(sql, parameters)
                : DatabaseHelper.ExecuteQuery(conn, tx, sql, parameters);

        /// <summary>Adds "AND (col1 LIKE @w0 OR col2 LIKE @w0) AND (...)" for every word typed in a search box.</summary>
        private static void AppendWords(StringBuilder sql, List<MySqlParameter> parameters, string? text, params string[] columns)
        {
            if (string.IsNullOrWhiteSpace(text)) return;
            string[] words = text.Split(' ', StringSplitOptions.RemoveEmptyEntries);
            for (int i = 0; i < words.Length; i++)
            {
                string name = "@w" + i.ToString(CultureInfo.InvariantCulture);
                sql.Append(" AND (").Append(string.Join(" OR ", columns.Select(c => c + " LIKE " + name))).Append(')');
                string escaped = words[i].Replace("\\", "\\\\").Replace("%", "\\%").Replace("_", "\\_");
                parameters.Add(DatabaseHelper.Param(name, "%" + escaped + "%"));
            }
        }

        private static PayableBill ReadBill(DataRow r) => new PayableBill
        {
            BillId = DatabaseHelper.GetString(r, "bill_id"),
            PatientId = DatabaseHelper.GetString(r, "patient_id"),
            PatientName = DatabaseHelper.GetString(r, "patient_name"),
            BillDate = DatabaseHelper.GetNullableDate(r, "finalized_at") ?? DateTime.Now,
            BillStatus = DatabaseHelper.GetString(r, "status"),
            GrandTotal = DatabaseHelper.GetDecimal(r, "grand_total"),
            AmountPaid = DatabaseHelper.GetDecimal(r, "amount_paid"),
            AmountRefunded = DatabaseHelper.GetDecimal(r, "amount_refunded"),
            Balance = DatabaseHelper.GetDecimal(r, "balance"),
            PaymentStatus = DatabaseHelper.GetString(r, "payment_status")
        };

        // ------------------------------------------------------------------
        // Lists
        // ------------------------------------------------------------------

        public List<PaymentMethod> GetMethods() => PaymentRules.Methods.ToList();

        /// <summary>Finalized bills that still have a balance (oldest first).</summary>
        public List<PayableBill> GetPayableBills(string? text)
        {
            var sql = new StringBuilder(SummarySelect + " AND s.status = '" + PaymentRules.BillFinalized + "' AND s.balance > 0");
            var parameters = new List<MySqlParameter>();
            AppendWords(sql, parameters, text, "s.bill_id", "p.patient_id", "p.first_name", "p.last_name");
            sql.Append(" ORDER BY b.finalized_at, b.bill_id LIMIT ").Append(PaymentRules.PayableLimit.ToString(CultureInfo.InvariantCulture));
            return DatabaseHelper.ExecuteQuery(sql.ToString(), parameters.ToArray()).Rows.Cast<DataRow>().Select(ReadBill).ToList();
        }

        public PayableBill? GetBill(string billId)
        {
            DataTable table = DatabaseHelper.ExecuteQuery(SummarySelect + " AND s.bill_id = @id", DatabaseHelper.Param("@id", billId));
            return table.Rows.Count == 0 ? null : ReadBill(table.Rows[0]);
        }

        /// <summary>
        /// Billing Records: every finalized bill, filtered by bill ID / patient (words), bill date range and payment status.
        /// paymentStatus: "" = all, otherwise Outstanding, Partially Paid, Fully Paid or Voided.
        /// </summary>
        public List<PayableBill> GetRecords(string? text, DateTime? from, DateTime? to, string? paymentStatus)
        {
            var sql = new StringBuilder(SummarySelect);
            var parameters = new List<MySqlParameter>();
            AppendWords(sql, parameters, text, "s.bill_id", "p.patient_id", "p.first_name", "p.last_name");
            if (from.HasValue)
            {
                sql.Append(" AND DATE(b.finalized_at) >= @from");
                parameters.Add(DatabaseHelper.Param("@from", from.Value.Date));
            }
            if (to.HasValue)
            {
                sql.Append(" AND DATE(b.finalized_at) <= @to");
                parameters.Add(DatabaseHelper.Param("@to", to.Value.Date));
            }
            if (!string.IsNullOrEmpty(paymentStatus))
            {
                sql.Append(" AND s.payment_status = @status");
                parameters.Add(DatabaseHelper.Param("@status", paymentStatus));
            }
            sql.Append(" ORDER BY b.finalized_at DESC, b.bill_id DESC LIMIT ").Append(PaymentRules.ListLimit.ToString(CultureInfo.InvariantCulture));
            return DatabaseHelper.ExecuteQuery(sql.ToString(), parameters.ToArray()).Rows.Cast<DataRow>().Select(ReadBill).ToList();
        }

        /// <summary>The full payment history of a bill (payments and refunds), oldest first.</summary>
        public List<PaymentRecord> GetPayments(string billId)
        {
            DataTable table = DatabaseHelper.ExecuteQuery(
                "SELECT pm.payment_id, pm.payment_type, pm.amount, pm.reference_number, pm.tendered_amount, pm.payment_datetime, " +
                "       pm.payment_method AS method_name, u.full_name AS received_by, pm.refund_of_payment_id, pm.remarks, " +
                "       (SELECT COALESCE(SUM(r.amount), 0) FROM payments r " +
                "        WHERE r.refund_of_payment_id = pm.payment_id AND r.payment_type = 'Refund') AS refunded " +
                "FROM payments pm " +
                "JOIN users u ON u.user_id = pm.received_by_user_id " +
                "WHERE pm.bill_id = @id ORDER BY pm.payment_datetime, pm.payment_id",
                DatabaseHelper.Param("@id", billId));

            return table.Rows.Cast<DataRow>().Select(r => new PaymentRecord
            {
                PaymentId = DatabaseHelper.GetString(r, "payment_id"),
                PaymentType = DatabaseHelper.GetString(r, "payment_type"),
                RefundOfPaymentId = DatabaseHelper.GetString(r, "refund_of_payment_id"),
                Remarks = DatabaseHelper.GetString(r, "remarks"),
                Refunded = DatabaseHelper.GetDecimal(r, "refunded"),
                Amount = DatabaseHelper.GetDecimal(r, "amount"),
                MethodName = DatabaseHelper.GetString(r, "method_name"),
                ReferenceNumber = DatabaseHelper.GetString(r, "reference_number"),
                Tendered = r["tendered_amount"] == DBNull.Value ? null : DatabaseHelper.GetDecimal(r, "tendered_amount"),
                ReceivedBy = DatabaseHelper.GetString(r, "received_by"),
                PaidAt = DatabaseHelper.GetNullableDate(r, "payment_datetime") ?? DateTime.Now
            }).ToList();
        }

